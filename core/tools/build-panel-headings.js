#!/usr/bin/env node
'use strict';
// RelAI core / narzedzie: build-panel-headings — naglowki Kalamem panelu relai-panel.
//
// Po co: silnik modow nie ma rozmiaru ani kroju fontu w Text (2.1.293, sonda E8), a Svg rysuje
// osadzony font. Lista naglowkow mieszka w core/panel/theme.mjs (HEADINGS); to narzedzie
// rysuje je skryptem core/tools/panel-headings.py (fontTools: font przyciety do liter napisu,
// szerokosc z metryk fontu) i zapisuje core/panel/headings.mjs. Potem sync-panel-core.js
// kopiuje go do pluginu jak reszte rdzenia. Uruchamiasz tylko po zmianie HEADINGS albo fontu.
//
//   node core/tools/build-panel-headings.js            # wymaga: pip install fonttools brotli
//
// Kod wyjscia: 0 = zapisane, 1 = brak Pythona/fontTools albo litera spoza fontu. Komunikaty ASCII.

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'core', 'panel', 'headings.mjs');
const FONTS = path.join(ROOT, 'core', 'templates', 'HTML_PLAN', 'fonty');

async function main() {
  const { HEADINGS } = require(path.join(ROOT, 'core', 'panel', 'theme.mjs'));
  const py = spawnSync(process.env.PYTHON || 'python', [path.join(__dirname, 'panel-headings.py'), FONTS],
    { input: JSON.stringify(HEADINGS), encoding: 'utf8', maxBuffer: 16 * 1024 * 1024,
      env: { ...process.env, PYTHONIOENCODING: 'utf-8' } }); // a Windows console code page would mangle the Polish letters
  if (py.status !== 0) {
    process.stderr.write('[build-panel-headings] panel-headings.py: ' + (py.stderr || py.error || 'brak Pythona') + '\n');
    process.exit(1);
  }
  const drawn = JSON.parse(py.stdout);
  const byKey = Object.fromEntries(drawn.map((d) => [d.key, d]));
  const body = [
    '// RelAI core / panel: headings — GENERATED by core/tools/build-panel-headings.js from theme.mjs',
    '// (HEADINGS). Do not edit: change HEADINGS and run the tool. Each value is an SVG with Kalam',
    '// subset to its own text; width, height and textWidth are CSS pixels measured from the font.',
    '',
    '/** @type {Readonly<Record<string, { text: string, width: number, height: number, textWidth: number, x: number, svg: string }>>} */',
    'export const HEADING_ART = Object.freeze(' + JSON.stringify(byKey, null, 1) + ');',
    '',
  ].join('\n');
  fs.writeFileSync(OUT, body);
  const chars = drawn.reduce((n, d) => n + d.svg.length, 0);
  process.stdout.write('[build-panel-headings] zapisane: ' + drawn.length + ' naglowkow, ' + chars + ' znakow SVG -> core/panel/headings.mjs\n');
}

main().catch((err) => { process.stderr.write('[build-panel-headings] ' + err.message + '\n'); process.exit(1); });
