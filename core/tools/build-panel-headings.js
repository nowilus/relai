#!/usr/bin/env node
'use strict';
// RelAI core / narzedzie: build-panel-headings — naglowki Kalamem panelu relai-panel.
//
// Po co: silnik modow nie ma rozmiaru ani kroju fontu w Text (2.1.293, sonda E8), a Svg rysuje
// osadzony font. Lista naglowkow mieszka w core/panel/theme.mjs (HEADINGS); to narzedzie
// rysuje je skryptem core/tools/panel-headings.py (fontTools: font przyciety do liter napisu,
// szerokosc z metryk fontu) i zapisuje zasoby oraz zgodny eksportami barrel headings.mjs.
// sync-panel-core.js kopiuje osiagalne zasoby per mod. Uruchamiasz po zmianie HEADINGS albo fontu.
//
//   node core/tools/build-panel-headings.js            # wymaga: pip install fonttools brotli
//
// Kod wyjscia: 0 = zapisane, 1 = brak Pythona/fontTools albo litera spoza fontu. Komunikaty ASCII.

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'core', 'panel', 'headings.mjs');
const FONTS = path.join(ROOT, 'core', 'templates', 'HTML_PLAN', 'fonty');

// Keep the public barrel, but let each consumer import only its own assets. The graph-based
// sync follows these imports; no second copy list belongs in sync-panel-core.js.
function writeModules({ HEADING_ART, NUMERALS, LABELS, LABEL_CAP }) {
  const banner = '// GENERATED by core/tools/build-panel-headings.js. Do not edit.\n';
  const write = (name, body) => fs.writeFileSync(path.join(ROOT, 'core', 'panel', name), banner + body + '\n');
  const art = (keys) => '/** @type {Readonly<Record<string, { text: string, width: number, height: number, textWidth: number, x: number, svg: string }>>} */\nexport const HEADING_ART = Object.freeze(' + JSON.stringify(Object.fromEntries(keys.map(k => [k, HEADING_ART[k]])), null, 1) + ');';
  write('heading-art.mjs', art(Object.keys(HEADING_ART)));
  write('headings-progress.mjs', art(['agents']));
  write('headings-mods.mjs', art(['mods-mod', 'mods-plugin', 'mods-hook']));
  write('numerals.mjs', '/** @type {Readonly<{ weight: number, font: string, advances: Readonly<Record<string, number>> }>} */\nexport const NUMERALS = Object.freeze(' + JSON.stringify(NUMERALS, null, 1) + ');');
  write('labels.mjs', '/** @type {Readonly<Record<string, { d: string, advance: number }>>} */\nexport const LABELS = Object.freeze(' + JSON.stringify(LABELS) + ');\nexport const LABEL_CAP = ' + LABEL_CAP + ';');
  fs.writeFileSync(OUT, banner + "export { HEADING_ART } from './heading-art.mjs';\nexport { NUMERALS } from './numerals.mjs';\nexport { LABELS, LABEL_CAP } from './labels.mjs';\n");
}

async function main() {
  const { HEADINGS, NUMERAL_GLYPHS, LABEL_GLYPHS } = require(path.join(ROOT, 'core', 'panel', 'theme.mjs'));
  const items = [...HEADINGS, { key: 'numerals', glyphs: NUMERAL_GLYPHS }, { key: 'labels', outlines: LABEL_GLYPHS }];
  const py = spawnSync(process.env.PYTHON || 'python', [path.join(__dirname, 'panel-headings.py'), FONTS],
    { input: JSON.stringify(items), encoding: 'utf8', maxBuffer: 16 * 1024 * 1024,
      env: { ...process.env, PYTHONIOENCODING: 'utf-8' } }); // a Windows console code page would mangle the Polish letters
  if (py.status !== 0) {
    process.stderr.write('[build-panel-headings] panel-headings.py: ' + (py.stderr || py.error || 'brak Pythona') + '\n');
    process.exit(1);
  }
  const all = JSON.parse(py.stdout);
  const numerals = all.find((d) => d.key === 'numerals');
  const labels = all.find((d) => d.key === 'labels');
  const drawn = all.filter((d) => d !== numerals && d !== labels);
  const byKey = Object.fromEntries(drawn.map((d) => [d.key, d]));
  writeModules({ HEADING_ART: byKey, NUMERALS: { weight: numerals.weight, font: numerals.font, advances: numerals.advances }, LABELS: labels.glyphs, LABEL_CAP: labels.capHeight });
  const chars = drawn.reduce((n, d) => n + d.svg.length, 0);
  process.stdout.write('[build-panel-headings] zapisane: ' + drawn.length + ' naglowkow, ' + chars + ' znakow SVG -> core/panel/headings.mjs\n');
}

if (require.main === module) main().catch((err) => { process.stderr.write('[build-panel-headings] ' + err.message + '\n'); process.exit(1); });
module.exports = { writeModules };
