# RelAI core / narzedzie: build-hanken-name — kontury liter Hanken Grotesk dla imienia agenta.
#
# Po co: tekst modu nie ma kroju ani rozmiaru, a imie na karcie RelAI Agents ma byc wyraznie
# wieksze od reszty (odnoga AGENTS_KRABY, 2026-10-23: Lukasz wybral Hanken zamiast piksela).
# Kontury liter (bez osadzonego fontu) skladane w czasie dzialania w <defs>/<use> waza kilka KB
# na karte. Font zmienny przyciety do jednej grubosci (wght NAME_WEIGHT), wspolrzedne w jednostkach
# fontu (1000 na em) zaokraglone do calych, os y w gore.
#
#   python core/tools/build-hanken-name.py      # wymaga: pip install fonttools brotli
#
# Zapisuje core/panel/hanken.mjs; potem node core/tools/sync-panel-core.js. Komunikaty ASCII.

import json
import os
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
FONTS = os.path.join(ROOT, 'core', 'templates', 'HTML_PLAN', 'fonty')
OUT = os.path.join(ROOT, 'core', 'panel', 'hanken.mjs')
NAME_WEIGHT = 650
CHARS = ('ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz'
         'ĄĆĘŁŃÓŚŹŻąćęłńóśźż0123456789 .-\'…')

faces = []
for part in ('latin', 'latin-ext'):
    font = TTFont(os.path.join(FONTS, f'hanken-grotesk-{part}.woff2'))
    faces.append(instantiateVariableFont(font, {'wght': NAME_WEIGHT}))

upm = faces[0]['head'].unitsPerEm
glyphs = {}
for ch in CHARS:
    for f in faces:
        name = f.getBestCmap().get(ord(ch))
        if name:
            pen = SVGPathPen(f.getGlyphSet(), lambda v: str(round(v * 1000 / upm)))
            f.getGlyphSet()[name].draw(pen)
            glyphs[ch] = [pen.getCommands(), round(f['hmtx'][name][0] * 1000 / upm)]
            break
    else:
        sys.exit(f'[build-hanken-name] Hanken Grotesk has no glyph for {ch!r}')

os2 = faces[0]['OS/2']
meta = {'cap': round(os2.sCapHeight * 1000 / upm), 'ascender': round(os2.sTypoAscender * 1000 / upm),
        'descender': round(-os2.sTypoDescender * 1000 / upm)}
body = [
    '// RelAI core / panel: hanken — GENERATED by core/tools/build-hanken-name.py. Do not edit.',
    f'// Hanken Grotesk (SIL OFL 1.1) at wght {NAME_WEIGHT}: each letter its outline in font units',
    '// (1000 an em, y up) and its advance; the RelAI Agents card draws a name with them.',
    f'export const HANKEN_META = Object.freeze({json.dumps(meta)});',
    f'export const HANKEN = Object.freeze({json.dumps(glyphs, ensure_ascii=False)});',
    '',
]
with open(OUT, 'w', encoding='utf-8', newline='\n') as out:
    out.write('\n'.join(body))
print(f'[build-hanken-name] zapisano core/panel/hanken.mjs: {len(glyphs)} liter')
