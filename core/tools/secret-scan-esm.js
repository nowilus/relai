'use strict';
// RelAI core / tool: secret-scan-esm — the ESM copy of core/guardrails/secret-scan.js for mods
// (plan MODY_OSZCZEDZANIA, E1). A mod may import only files inside its folder and only ESM,
// while the hooks of three adapters and git pre-commit load the scanner as CommonJS. The
// patterns keep ONE source: secret-scan.js. This tool cuts its CommonJS frame (shebang,
// 'use strict', module.exports and the CLI block) and adds an ESM export; sync-panel-core.js
// writes the result as secret-scan.mjs into the copy folder of each mod that imports it, and
// --check compares it, as it does for icons.mjs. The copy is never edited by hand.

const fs = require('fs');
const path = require('path');

const SOURCE = path.resolve(__dirname, '..', 'guardrails', 'secret-scan.js');
const EXPORT_LINE = 'module.exports = { scanText, PATTERNS };';
const HEADER = '// GENERATED by core/tools/secret-scan-esm.js from core/guardrails/secret-scan.js — do not edit.\n';

/** ESM text of the scanner from the CommonJS source text. Throws when the frame changed. */
function toEsm(sourceText) {
  const text = String(sourceText).replace(/\r\n/g, '\n');
  const cut = text.indexOf(EXPORT_LINE);
  if (cut < 0) throw new Error('secret-scan-esm: export line not found in secret-scan.js');
  const body = text.slice(0, cut)
    .replace(/^#!.*\n/, '')
    .replace(/^'use strict';\n/m, '');
  if (/\brequire\s*\(/.test(body)) throw new Error('secret-scan-esm: the scanner body calls require()');
  return `${HEADER}${body}export { scanText, PATTERNS };\n`;
}

function build() {
  return toEsm(fs.readFileSync(SOURCE, 'utf8'));
}

module.exports = { toEsm, build, SOURCE };
